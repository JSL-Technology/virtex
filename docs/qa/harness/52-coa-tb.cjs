const { launch, instrument, uiLogin, shot, go, panel, panelText, netSince, stepUpAll } = require('./lib.cjs');
(async () => {
  const { browser, context } = await launch();
  const page = await context.newPage();
  const log = instrument(page);
  page.on('dialog', (d) => { console.log('DIALOG', d.message()); d.accept(); });
  await uiLogin(page);
  const p = panel(page);
  const probe = async (tag, fn) => { const n = log.requests.length; const a = (await panelText(page)).length; const u = page.url(); try { await fn(); } catch (e) { console.log(`[${tag}] EXC ${e.message.split('\n')[0]}`); return; } await page.waitForTimeout(1400); const su = await stepUpAll(page); const b = (await panelText(page)).length; console.log(`[${tag}] stepups=${su} texto ${a}->${b} url=${page.url() !== u ? page.url().split('/e/')[1] : '='} red=${netSince(log, n).map((x) => x.slice(0, 100)).join(' ; ').slice(0, 300)}`); };
  await go(page, 'accounting/chart-of-accounts'); await page.waitForTimeout(1500);
  const sels = p.locator('select');
  console.log('FILTROS', JSON.stringify(await sels.evaluateAll((ss) => ss.map((s) => [...s.options].map((o) => o.text.trim())))));
  await probe('filtro-estado-inactiva', () => sels.nth(0).selectOption({ label: 'Inactiva' }));
  await probe('filtro-estado-todos', () => sels.nth(0).selectOption({ index: 0 }));
  await probe('filtro-tipo-gasto', () => sels.nth(1).selectOption({ label: 'Gasto' }));
  await probe('filtro-tipo-todos', () => sels.nth(1).selectOption({ index: 0 }));
  for (const h of ['CUENTA', 'TIPO', 'BALANCE', 'ESTADO']) await probe(`orden-${h}`, () => p.locator('th').filter({ hasText: h }).first().click());
  await probe('expandir-gastos', () => p.getByText('Gastos', { exact: true }).first().click());
  await probe('expandir-5000', () => p.getByText('5000', { exact: true }).first().click());
  console.log('ARBOL', (await panelText(page)).replace(/\n+/g, ' | ').slice(0, 600));
  await probe('editar-primera', () => p.getByText('Editar').first().click());
  console.log('EDIT', (await panelText(page)).replace(/\n+/g, ' | ').slice(0, 300));
  await go(page, 'reports/financial-statements/trial-balance'); await page.waitForTimeout(1500);
  for (const h of ['Cuenta', 'Saldo inicial', 'Debe']) await probe(`tb-th-${h}`, () => p.locator('th').filter({ hasText: h }).first().click());
  await probe('tb-fila-1120', () => p.getByText('1120 Bancos').first().click());
  const dates = p.locator('input[type=date]');
  await probe('tb-rango-invertido', async () => { await dates.nth(0).fill('2026-12-31'); await dates.nth(1).fill('2026-01-01'); await p.getByRole('button', { name: 'Actualizar' }).click(); });
  console.log('TB-INVERTIDO', (await panelText(page)).replace(/\n+/g, ' | ').slice(0, 300));
  await shot(page, 'f-tb-invertido');
  await browser.close();
})();
